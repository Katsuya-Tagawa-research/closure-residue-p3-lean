    q=real_parity_parameters(d)[2]
    lifted=add(ev,scale(ODD,gc(q)))
    assert lifted==d
    assert H1(lifted)==H1(d) and H2(lifted)==H2(d)
    # Check actual one-step, two-step and higher P3 hidden history
