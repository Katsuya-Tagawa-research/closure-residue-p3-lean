"""H83 exact symbolic rational polynomial audit; no extra dependencies.

A four-cell periodic canonical scalar ring is an independently supplied
comparator; neither spatial coupling nor the physical K4 solder is
asserted generated by the P3 micro-source.
"""
from fractions import Fraction as F
n=4
nvar=4*n
z=(0,)*nvar

class Poly:
    def __init__(self, terms=None):
        self.t={m:F(c) for m,c in (terms or {}).items() if c}
    @staticmethod
    def const(c):
        return Poly({z:F(c)}) if c else Poly()
    @staticmethod
    def var(i):
        e=list(z); e[i]=1
        return Poly({tuple(e):F(1)})
    def __add__(self,b):
        if not isinstance(b,Poly):b=Poly.const(b)
        d=self.t.copy()
        for m,c in b.t.items():
            d[m]=d.get(m,F(0))+c
            if not d[m]:del d[m]
        return Poly(d)
    __radd__=__add__
    def __neg__(self):return Poly({m:-c for m,c in self.t.items()})
    def __sub__(self,b):return self+(-b if isinstance(b,Poly) else -F(b))
    def __rsub__(self,b):return b+-self
    def __mul__(self,b):
        if not isinstance(b,Poly):b=Poly.const(b)
        d={}
        for x,c in self.t.items():
            for y,e in b.t.items():
                k=tuple(i+j for i,j in zip(x,y))
                d[k]=d.get(k,F(0))+c*e
        return Poly(d)
    __rmul__=__mul__
    def diff(self,i):
        d={}
        for m,c in self.t.items():
            if m[i]:
                k=list(m);k[i]-=1
                d[tuple(k)]=c*m[i]
        return Poly(d)
    def eval(self,values):
        assert len(values)==nvar
        return sum((c*product(F(v)**e for v,e in zip(values,m))
                    for m,c in self.t.items()),F(0))
    def __eq__(self,b):
        return self.t==(b.t if isinstance(b,Poly) else Poly.const(b).t)

def product(x):
    y=F(1)
    for a in x:y*=a
    return y

q=[Poly.var(i) for i in range(n)]
p=[Poly.var(i+n) for i in range(n)]
N=[Poly.var(i+2*n) for i in range(n)]
M=[Poly.var(i+3*n) for i in range(n)]
A=F(3,2)
kappa=F(5,3)

def PB(f,g):
    return sum((f.diff(i)*g.diff(i+n)-f.diff(i+n)*g.diff(i)
                for i in range(n)),Poly())

def Hu(L):
    return sum((L[i]*(A/2*p[i]*p[i]+F(7,6)*q[i]*q[i])
                for i in range(n)),Poly())

assert PB(Hu(N),Hu(M))==0
print("PASS H83.1: ultralocal H-H zero polynomial for arbitrary lapses and cell states")

def He(L):
    return sum((A/2*L[i]*p[i]*p[i]
        +kappa/4*(L[i]+L[(i+1)%n])*(q[(i+1)%n]-q[i])*(q[(i+1)%n]-q[i])
               for i in range(n)),Poly())

HH=PB(He(N),He(M))
flux=sum((A*kappa/2*(N[i]*M[(i+1)%n]-M[i]*N[(i+1)%n])
    *(p[i]+p[(i+1)%n])*(q[(i+1)%n]-q[i])
    for i in range(n)),Poly())
assert HH==flux
print("PASS H83.2: arbitrary-state, arbitrary-lapse polynomial edge-flux H-H identity")

state=[F(0),F(1,2),F(1,3),F(-1,4), F(1),F(2),F(-1),F(3),
       F(1),F(0),F(2),F(-1), F(0),F(1),F(-1),F(2)]
assert HH.eval(state)==F(-55,12)
print("PASS H83.3: nonzero off-shell lapse-antisymmetric bracket -55/12")

# M symbols now label independent edge shifts b_i for the D-H witness.
b=M
D=sum((F(1,2)*b[i]*(p[i]+p[(i+1)%n])*(q[(i+1)%n]-q[i])
       for i in range(n)),Poly())
lapse_shift=[F(1,4)*(b[(i-1)%n]+b[i])*(N[(i+1)%n]-N[(i-1)%n])
             for i in range(n)]
DH=PB(D,He(N))
target=He(lapse_shift)
v2=state[:12]+[F(2),F(0),F(1),F(-1)]
assert DH.eval(v2)==F(-31679,1728)
assert target.eval(v2)==F(149,96)
assert (DH-target).eval(v2)==F(-34361,1728)
print("PASS H83.4: naive finite D-H mismatch -34361/1728, not a general no-go")

# Given a separately soldered covector v in S=1^perp,
# g_w^{-1}=A_w/16 and A_w=sum w_ab (e_a-e_b)(e_a-e_b)^T.
v=(F(1,2),F(1,2),F(-1,2),F(-1,2))
edges=[(0,1),(0,2),(0,3),(1,2),(1,3),(2,3)]
weights=[1,2,1,3,2,1]
assert sum(v)==0 and sum(x*x for x in v)==1
assert sum((v[a]-v[c])**2 for a,c in edges)==4
assert sum(F(w)*(v[a]-v[c])**2 for w,(a,c) in zip(weights,edges))/16==F(1,2)
print("PASS H83.5: conditional K4 matter inverse-metric contraction uniform=1/4, nonuniform=1/2")
