#!/usr/bin/env python3
"""P11 AX05 exact finite operator observability, not an apparatus validation."""
from pathlib import Path
import json
import sympy as s

checks=[]
def check(condition,label):
    assert bool(condition),label
    checks.append(label)
def E(n,i,j):
    m=s.zeros(n);m[i,j]=1;return m
def eq(A,B):
    return A.shape==B.shape and all(s.simplify(x)==0 for x in A-B)
def vec(M):
    return s.Matrix([M[i,j] for j in range(M.cols) for i in range(M.rows)])
def rank(M):
    return s.Matrix.hstack(*[vec(m) for m in M]).rank() if M else 0
def equal_span(A,B):
    return rank(A)==rank(B)==rank(A+B)

I=s.eye(2);X=E(2,0,1)+E(2,1,0);Y=-s.I*E(2,0,1)+s.I*E(2,1,0);Z=E(2,0,0)-E(2,1,1)
U=s.diag(1,s.I)
Psi=lambda A:U.H*A*U
Mx=[(I+X)/2,(I-X)/2]
Mz=[(I+Z)/2,(I-Z)/2]
for i,m in enumerate(Mx+Mz):
    check(eq(m.H,m),f'POVM effect Hermitian {i}')
    check(eq(m*m,m),f'projective effect {i}')
check(eq(sum(Mx,s.zeros(2)),I),'X POVM normalized')
check(eq(sum(Mz,s.zeros(2)),I),'Z POVM normalized')
check(eq(Psi(X),-Y),'quarter-turn sends X to -Y')
check(eq(Psi(Y),X),'quarter-turn sends Y to X')
check(eq(Psi(Z),Z),'quarter-turn fixes Z')
check(eq(Psi(I),I),'quarter-turn fixes unit')
qubit=[Mx[0],Mx[1]]
qubit_ranks=[]
for step in range(5):
    qubit_ranks.append(rank(qubit))
    check(rank(qubit)==(2 if step==0 else 3),f'X-only operational rank {step}')
    qubit += [Psi(a) for a in qubit]
check(qubit_ranks==[2,3,3,3,3],'X-only orbit rank tower')
check(equal_span(qubit,[I,X,Y]),'X-only operational span I X Y')
check(rank([I,X,Y,Z])==4,'all qubit operators span dimension4')
check(eq(X*Y,s.I*Z),'nonaccessible Z generated by product X Y')
check(not equal_span(qubit,qubit+[Z]),'Z not operationally accessible as linear stat')
rho0=(I+Z)/2;rho1=(I-Z)/2
check(eq(rho0.H,rho0) and eq(rho1.H,rho1),'indistinguishable candidates valid states')
check(s.trace(rho0)==s.trace(rho1)==1,'candidate states normalized')
check(not eq(rho0,rho1),'candidates distinct')
for k in range(4):
    for j,m in enumerate(Mx):
        eff=m
        for _ in range(k):eff=Psi(eff)
        check(s.simplify(s.trace(eff*rho0)-s.trace(eff*rho1))==0,f'X-only equal stats word {k} effect {j}')
check(s.simplify(s.trace(Mz[0]*rho0)-s.trace(Mz[0]*rho1))==1,'independent Z POVM resolves states')
qubit_full=qubit+[Mz[0],Mz[1]]
check(rank(qubit_full)==4,'X orbit plus Z native detector is informationally complete')

n=5;p=[E(n,i,i) for i in range(n)]
pairs=[(i,j) for i in range(n) for j in range(i+1,n)]
Xs=[E(n,i,j)+E(n,j,i) for i,j in pairs]
Ys=[-s.I*E(n,i,j)+s.I*E(n,j,i) for i,j in pairs]
basis=p+Xs+Ys
assert len(basis)==n*n
edges=[E(n,i,i+1)+E(n,i+1,i) for i in range(n-1)]
H=s.diag(0,s.Rational(1,7),-s.Rational(1,9),s.Rational(2,11),-s.Rational(3,13))+sum(edges,s.zeros(n))/2
g=s.Rational(2,3)
Delta=lambda A:s.diag(*[A[i,i] for i in range(n)])
Ldag=lambda A:s.I*(H*A-A*H)+g*(Delta(A)-A)
def coordinates(A):
    di=[s.simplify(A[i,i]) for i in range(n)]
    xc=[s.simplify((A[i,j]+A[j,i])/2) for i,j in pairs]
    yc=[s.simplify((A[j,i]-A[i,j])/(2*s.I)) for i,j in pairs]
    return s.Matrix(di+xc+yc)
def reconstitute(c):
    return sum((basis[i]*c[i] for i in range(n*n)),s.zeros(n))
check(eq(H,H.H),'H37 baseline selfadjoint')
for i,a in enumerate(basis):
    check(eq(reconstitute(coordinates(a)),a),f'Hermitian basis coordinate reconstitution {i}')
    check(eq(Ldag(a),Ldag(a).H),f'H37 generator preserves Hermitian basis {i}')
T=s.Matrix.hstack(*[coordinates(Ldag(a)) for a in basis])
check(all(x.is_Rational for x in T),'H37 observable generator rational real coordinates')
check(T.shape==(25,25),'H37 observable generator 25x25')
check(T[:,0:5].rank()==4,'first derivatives of populations rank4')
initial=s.eye(n*n)[:,:5]; Kry=initial; Xk=initial
ranks=[Kry.rank()]
for k in range(1,8):
    Xk=T*Xk
    Kry=Kry.row_join(Xk)
    ranks.append(Kry.rank())
    check(ranks[-1]>=ranks[-2],f'Krylov rank monotone step {k}')
check(ranks==[5,9,13,17,21,23,25,25],f'H37 exact Krylov ranks {ranks}')
check(Kry.rank()==25,'H37 ideal time-resolved population span M5')
check(initial.rank()==5,'H37 zero-time population rank5')
check((T*initial).rank()==4,'H37 first derivative population rank4')
check(T*coordinates(s.eye(n))==s.zeros(n*n,1),'unital generator fixes I')
check(all(coordinates(Ldag(pi))==T*coordinates(pi) for pi in p),'H37 generator coordinate conjugacy')
check(T.det()==0,'H37 Heisenberg generator has fixed identity')
check(not equal_span([I,X,Y],[I,X,Y,Z]),'operational versus algebra gap persists')
check(rank([I,X,Y])==3,'qubit linear orbit dimension3')
check(rank([I,X,Y,X*Y])==4,'adding multiplication gives full algebra')
check(rank([I,X,Y,Z])==4,'qubit full tomography dimensional criterion')

out={
 'study':'P11-AX05','all_passed':True,'checks_passed':len(checks),'checks':checks,
 'qubit_operational_X_orbit_ranks':qubit_ranks,
 'qubit_operational_dimension':3,'qubit_generated_star_algebra_dimension':4,
 'qubit_X_Z_two_detector_operational_dimension':4,
 'H37_population_generator_Krylov_ranks':ranks,
 'H37_ideal_time_resolved_effect_dimension':25,
 'H37_initial_population_effect_dimension':5,
 'hardware_measurement_instruments':'NOT CERTIFIED',
 'P6_native_phase_and_readout':'OPEN',
 'P3_Rk_identification':'OPEN',
 'P11_generative_completeness':'OPEN'
}
Path(__file__).with_name('P11_AX05_exact_results.json').write_text(json.dumps(out,indent=2,ensure_ascii=False)+'\n')
print(f'P11 AX05 PASS: {len(checks)}/{len(checks)} exact assertions')
print('Qubit operational 3 < algebra 4; H37 generator Krylov:',ranks)
