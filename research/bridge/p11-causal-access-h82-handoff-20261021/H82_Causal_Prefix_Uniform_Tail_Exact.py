print("PASS: each one-cycle no-event branch satisfies the same b=5/6 bound")
print("PASS: four adaptive A/B schedules, 3 positive inputs, prefixes through 4")
print("PASS: each event-time distribution conserves event+survival mass exactly")
print("PASS: every tested CP branch prefix has an exact Heisenberg effect")
print("PASS: worst-case 1% tail K=26; separate 27-symbol overflow record")
