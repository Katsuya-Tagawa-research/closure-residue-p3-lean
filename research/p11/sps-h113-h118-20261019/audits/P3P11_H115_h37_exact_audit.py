#!/usr/bin/env python3
"""H115 exact H37 finite-matrix audit. Uses only SymPy and rational arithmetic.
Generator Krylov filtration, not a claim of literal grade-by-grade equality with P3's exp(tL) filtration.
"""
import json
import sympy as s
from pathlib import Path

N=5
Q=s.Rational
I=s.I
E=lambda a,b: s.eye(N)[:,a]*s.eye(N)[b,:]
p=[E(a,a) for a in range(N)]
X=[E(a,a+1)+E(a+1,a) for a in range(N-1)]
K=[E(a,a+1)-E(a+1,a) for a in range(N-1)]
Hhop=Q(1,2)*sum(X,s.zeros(N))
H=s.diag(Q(0),Q(1,7),-Q(1,9),Q(2,11),-Q(3,13))+Hhop
gamma=Q(2,3)
DD=lambda A:s.diag(*[A[i,i] for i in range(N)])
OFF=lambda A:A-DD(A)
def L(A):return s.expand(-I*(H*A-A*H)+gamma*(DD(A)-A))
pairs=[(a,b) for a in range(N) for b in range(a+1,N)]

def herm_coords(A,inc_diag=False):
    assert A==A.conjugate().T
    seq=([s.re(A[a,a]) for a in range(N)] if inc_diag else [])
    seq+=sum(([s.expand(s.re(A[a,b])),s.expand(s.im(A[a,b]))] for a,b in pairs),[])
    return s.Matrix(seq)

def anti_coords(A):
    assert A == -A.conjugate().T
    assert DD(A)==s.zeros(N)
    return s.Matrix(sum(([s.expand(s.re(A[a,b])),s.expand(s.im(A[a,b]))] for a,b in pairs),[]))

def generic_coords(A):
    return s.Matrix([A[a,b] for a in range(N) for b in range(N)])

def rank_of(mats,fun=generic_coords):
    if not mats:return 0
    return s.Matrix.hstack(*[fun(x) for x in mats]).rank()

# Native and algebraic closures
Jmix=[Hhop,*K]
Jfull=sum(([E(a,a+1),E(a+1,a)] for a in range(N-1)),[])
JnativeD=[p[a]*u*p[b] for a in range(N) for b in range(N) for u in K]
JmixD=[p[a]*u*p[b] for a in range(N) for b in range(N) for u in Jmix]
JhopD=[p[a]*Hhop*p[b] for a in range(N) for b in range(N)]
JhopD=[a for a in JhopD if a!=s.zeros(N)]
assert rank_of(K)==4
assert rank_of(Jmix)==5
assert rank_of(Jfull)==8
assert rank_of(JnativeD)==8
assert rank_of(JmixD)==8
assert rank_of(JhopD)==8
assert rank_of([p[0]*Hhop*p[1],*Jmix])==6 # Jmix is not D-bimodule
assert rank_of([*Jfull,*JnativeD])==8
assert rank_of([*Jfull,*JmixD])==8
assert rank_of([*Jfull,*JhopD])==8

# Xi(J): for complex span J include both basis B and iB as a real vector space.
def XI(A): return OFF(A-A.conjugate().T)
def xi_rank(mats):return rank_of([XI(A) for A in mats]+[XI(I*A) for A in mats],anti_coords)
assert xi_rank(Jmix)==5
assert xi_rank(Jfull)==8
assert xi_rank(K)==4

# Full diag quadratic residue rank for Jmix and full:
def diagcoords(A):return s.Matrix([A[a,a] for a in range(N)])
def comm(A,B):return A*B-B*A
quad_mix=[DD(comm(Hhop,x)) for x in K]
quad_full=[DD(comm(E(a,a+1),E(a+1,a))) for a in range(N-1)]
assert s.Matrix.hstack(*[diagcoords(x) for x in quad_mix]).rank()==4
assert s.Matrix.hstack(*[diagcoords(x) for x in quad_full]).rank()==4

# Bracket closure of native anti-Hermitian real skew K_e gives all so(5).
K_all=[E(a,b)-E(b,a) for a,b in pairs]
for a,b in pairs:
    assert K_all[pairs.index((a,b))].T==-K_all[pairs.index((a,b))]
assert rank_of(K_all)==10
# Each non-nearest K_ab generated by nested brackets along the path.
def nested(a,b):
    if b==a+1:return K[a]
    return comm(nested(a,b-1),K[b-1])
assert all(nested(a,b)==E(a,b)-E(b,a) for a,b in pairs)
lieD=[p[a]*v*p[b] for a in range(N) for b in range(N) for v in K_all]
assert rank_of(lieD)==20

# H37 generator Krylov filtration: all L^j(p_a), projected hidden and complete.
levels=[p]
rows=[]
for k in range(0,7):
    if k>0:levels.append([L(A) for A in levels[-1]])
    all_ops=sum(levels,[])
    mr=rank_of(all_ops,lambda A:herm_coords(A,inc_diag=True))
    hr=rank_of(all_ops,herm_coords)
    rows.append({'k':k,'M_rank':mr,'H_rank':hr})
assert [r['M_rank'] for r in rows]==[5,9,13,17,21,23,25]
assert [r['H_rank'] for r in rows]==[0,4,8,12,16,18,20]
assert L(p[0])[0,1]==I*Q(1,2)
assert L(L(p[0]))[0,2]==-Q(1,4) # non-nearest coherent direction at order 2

# Mod-p certificate: full 25x35 Hermitian-coordinate rank for L^0..L^6(D).
all_ops=sum(levels,[])
B=s.Matrix.hstack(*[herm_coords(A,inc_diag=True) for A in all_ops])
assert B.shape==(25,35)

def modular_pivots(A,pv):
    m,n=A.shape
    rows=[]; pivots=[]
    for j in range(n):
        v=[]
        for i in range(m):
            n0,d0=map(int,s.fraction(s.cancel(A[i,j])))
            v.append((n0*pow(d0,-1,pv))%pv)
        for lead,u in rows:
            if v[lead]:
                fac=v[lead]
                v=[(v[i]-fac*u[i])%pv for i in range(m)]
        lead=next((i for i,entry in enumerate(v) if entry),None)
        if lead is not None:
            inv=pow(v[lead],-1,pv)
            v=[(x*inv)%pv for x in v]
            rows.append((lead,v)); rows.sort(key=lambda item:item[0]);pivots.append(j)
            # normalize existing pivot rows wrt new pivot, to preserve echelon reduction
            new=[]
            for current_lead,u in rows:
                if current_lead==lead:new.append((current_lead,u))
                else:
                    fac=u[lead]
                    new.append((current_lead,[(u[i]-fac*v[i])%pv for i in range(m)]))
            rows=sorted(new)
    return pivots

# Simpler rank check via modular matrix independent of pivot selection (SymPy DomainMatrix).
def modrank(A,pv):
    entries=[]
    for v in A:
        numerator,denominator=s.fraction(s.cancel(v))
        entries.append((int(numerator)*pow(int(denominator),-1,pv))%pv)
    M=s.Matrix(A.rows,A.cols,entries)
    # explicit elimination to avoid SymPy rational-rank heuristics
    row=0
    for col in range(M.cols):
        pivot=next((r for r in range(row,M.rows) if int(M[r,col])%pv),None)
        if pivot is None:continue
        if pivot!=row:M.row_swap(pivot,row)
        scale=pow(int(M[row,col])%pv,-1,pv)
        for j in range(col,M.cols):M[row,j]=(int(M[row,j])*scale)%pv
        for r in range(row+1,M.rows):
            fac=int(M[r,col])%pv
            if fac:
                for j in range(col,M.cols):M[r,j]=(int(M[r,j])-fac*int(M[row,j]))%pv
        row+=1
        if row==M.rows:break
    return row
assert modrank(B,101)==25
assert modrank(B,1009)==25

