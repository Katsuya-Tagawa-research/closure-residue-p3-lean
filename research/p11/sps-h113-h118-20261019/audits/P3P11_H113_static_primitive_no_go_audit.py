"""H113: exact finite-dimensional demonstration, not an H37 verification.
Pure SymPy; run: python P3P11_H113_static_primitive_no_go_audit.py
"""
import sympy as sp

N = 3
E = lambda i,j: sp.eye(N)[:, i] * sp.eye(N)[j, :]
X12 = E(0,1)+E(1,0)
X23 = E(1,2)+E(2,1)
A, B = sp.I*X12, sp.I*X23
comm = lambda P,Q: P*Q-Q*P
C = comm(A, B)


def rank(*ms):
    return sp.Matrix.hstack(*(sp.Matrix(m).reshape(N*N,1) for m in ms)).rank()

# D_3-bimodule supports: Eii Xij Ejj projects onto Eij.
assert E(0,0)*X12*E(1,1) == E(0,1)
assert E(1,1)*X12*E(0,0) == E(1,0)
assert E(1,1)*X23*E(2,2) == E(1,2)
assert E(2,2)*X23*E(1,1) == E(2,1)
assert rank(E(0,1), E(1,0)) == 2
assert rank(E(0,1), E(1,0), E(1,2), E(2,1)) == 4

# Underlying Lie algebras generated by controls i X12 versus i X12 and i X23.
assert C == E(2,0)-E(0,2)
assert comm(A,C) == -B
assert comm(B,C) == A
assert rank(A,B,C) == 3
assert rank(A) == 1

# For id channel Phi, the rank-one Choi support is span{I}.
vec_I = sp.Matrix(sp.eye(N)).reshape(N*N,1)
choi_id = vec_I * vec_I.T
assert choi_id.rank() == 1
# The D_3-bimodule closure of span I is D_3 (no off-diagonal edges).
assert E(0,0)*sp.eye(N)*E(0,0) == E(0,0)
assert rank(E(0,0), E(1,1), E(2,2)) == 3
assert E(0,0)*sp.eye(N)*E(1,1) == sp.zeros(N)

# Diagonal phase projection is a weight projection (algebraic check).
u,v,w = sp.symbols('u v w', nonzero=True)
U=sp.diag(u,v,w)
Uinv=sp.diag(1/u,1/v,1/w)
assert U*E(0,1)*Uinv == (u/v)*E(0,1)
assert U*E(1,2)*Uinv == (v/w)*E(1,2)

