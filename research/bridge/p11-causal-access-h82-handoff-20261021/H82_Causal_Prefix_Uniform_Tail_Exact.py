"""Finite H82 handoff audit: labelled CP-prefix prediction and uniform tail.

Real H75 four Kraus operators, conditional site flag-SWAP, two selective
instruments. Complementary to prior original-H75 future effect rank and
cycle-CPTP audits from #182/#183; does NOT claim the predictive quotient
is a CPTP physical realization or access generated by F.
"""
import itertools
import sympy as s

R,I=s.Rational,s.I
I2,I3,I6=s.eye(2),s.eye(3),s.eye(6)
E=lambda j,k:I3[:,j]*I3[k,:]
O=s.Matrix([[R(2,3),R(2,3),-R(1,3)],
            [-R(2,3),R(1,3),-R(2,3)],
            [-R(1,3),R(2,3),R(2,3)]])
U=s.diag(I,1,I)*O
M=[s.diag(1,R(3,5),R(3,5)),s.diag(0,R(4,5),R(4,5))]
K=[s.kronecker_product(I2[:,a]*I2[b,:],U*M[a])
   for a,b in itertools.product(range(2),repeat=2)]
assert sum((v.H*v for v in K),s.zeros(6))==I6
L=[s.kronecker_product(I2,E(j,j)) for j in range(3)]
J=[(L[0]+L[1])/s.sqrt(2),(L[0]-L[1])/s.sqrt(2),L[2]]
F=s.kronecker_product(s.diag(1,0),I3)+s.kronecker_product(
  s.diag(0,1),E(0,1)+E(1,0)+E(2,2))
assert F.H*F==I6
W=[F,I6,I6]
branches={}
for name,ports in (("A",L),("B",J)):
    branches[name]=[[W[j]*ports[j]*v for v in K] for j in range(3)]
    assert sum((g.H*g for group in branches[name] for g in group),s.zeros(6))==I6
    assert sum((port.H*port for port in ports),s.zeros(6))==I6

def apply(ks,X):
    return sum((k*X*k.H for k in ks),s.zeros(6))
def dual(ks,E):
    return sum((k.H*E*k for k in ks),s.zeros(6))
def trace(X):
    return s.simplify(s.trace(X))

b=R(5,6)
assert b**25>R(1,100)>=b**26
assert b**26<=R(1,100)
for name in ("A","B"):
    z=dual(branches[name][0],I6)
    assert z.H==z
    # New per-cycle uniform bound, without claiming a physical law selecting ports.
    if name=="A":
        A=s.Matrix([[R(4,9),R(4,15),-R(2,15)],
                    [R(4,15),R(4,9),-R(2,9)],
                    [-R(2,15),-R(2,9),R(1,9)]])
        assert z==s.kronecker_product(I2,A)
        assert all((b*I3-A)[:j,:j].det()>0 for j in (1,2,3))
    else:
        assert z==sum((k.H*(L[0]+L[1])*k/2 for k in K),s.zeros(6))
        assert z==z.H and (I6/2-z)==dual(K,L[2])/2
        assert (I6/2-z).H==(I6/2-z)
        # A positive Kraus pullback explicitly proves z <= (1/2)I.

rho00=s.kronecker_product(s.diag(1,0),E(0,0))
rho01=s.kronecker_product(s.diag(1,0),E(1,1))
seeds=[I6/6,rho00,rho01]
for rho in seeds:
    assert rho.H==rho and trace(rho)==1
    for policy in (("A","A","A","A"),("B","B","B","B"),
                   ("A","B","A","B"),("B","A","B","A")):
        X=rho
        accumulated_event=R(0)
        prior=R(1)
        for n,name in enumerate(policy,1):
            later=apply(branches[name][0],X)
            event=trace(apply(branches[name][1],X)+apply(branches[name][2],X))
            remain=trace(later)
            assert remain.is_Rational and event.is_Rational
            assert 0<=event<=1 and 0<=remain<=1
            assert prior==event+remain
            accumulated_event+=event
            assert accumulated_event+remain==1
            assert remain<=b**n
            X=later
            prior=remain

# Heisenberg prefix probability factorization on the real H75 source:
# different instrument/schedule histories are exact physical linear effects.
for policy in (("A",),("B",),("A","B"),("B","A"),("B","A","B")):
    rho=rho01
    for c in policy:rho=apply(branches[c][0],rho)
    q=trace(rho)
    effect=I6
    for c in reversed(policy):effect=dual(branches[c][0],effect)
    # SymPy's raw Matrix equality is structural, not algebraically canonical.
    # Check the Hermitian and Born-duality identities after exact simplification.
    assert (effect-effect.H).applyfunc(s.simplify)==s.zeros(6), policy
    assert s.simplify(trace(effect*rho01)-q)==0, policy

# Strict distinction from a bounded exact event-time archive:
# K=26 bounds the tail; a truncation with an overflow output has
# 27 distinguishable classical output labels (k=1,...,26, overflow).
horizon=26
assert horizon+1==27
